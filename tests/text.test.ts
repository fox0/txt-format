import { it, expect } from 'vitest';
import { processText } from '../src/text';

function expectBoth(input: string, expected: string): asserts expected is string {
    expect(processText(input)).toBe(expected);

    const inputCapitalized = input.charAt(0).toUpperCase() + input.slice(1);
    const expectedCapitalized = expected.charAt(0).toUpperCase() + expected.slice(1);
    expect(processText(inputCapitalized)).toBe(expectedCapitalized);
}

